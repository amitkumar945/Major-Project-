const ENGLISH_KEYS = Object.keys(HINDI).sort((left, right) => right.length - left.length)
const originalText = new WeakMap()
const originalAttributes = new WeakMap()
let language = 'en'
let observer
let toggle
let originalTitle = ''

function readLanguage() {
  try {
    return window.localStorage.getItem(LANGUAGE_KEY) === 'hi' ? 'hi' : 'en'
  } catch {
    return 'en'
  }
}

function translate(text) {
  if (language !== 'hi' || !text.trim()) return text
  const leading = text.match(/^\s*/)?.[0] ?? ''
  const trailing = text.match(/\s*$/)?.[0] ?? ''
  const content = text.slice(leading.length, text.length - trailing.length)
  const normalized = content.replace(/\s+/g, ' ')
  const exact = HINDI[normalized]
  if (exact) return leading + exact + trailing

  let translated = content
  ENGLISH_KEYS.forEach((key) => {
    const isPhrase = /\s/.test(key) || key.length > 12
    if (!isPhrase) return
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const whitespaceFlexible = escaped.replace(/\s+/g, '\\s+')
    translated = translated.replace(new RegExp(whitespaceFlexible, 'gi'), HINDI[key])
  })
  return leading + translated + trailing
}

function translateTitle(title) {
  if (language !== 'hi') return title
  let translated = translate(title)
  ENGLISH_KEYS.filter((key) => !/\s/.test(key) && key.length <= 12).forEach((key) => {
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    translated = translated.replace(new RegExp(`\\b${escaped}\\b`, 'gi'), HINDI[key])
  })
  return translated
}

function ignoredText(node) {
  const parent = node.parentElement
  return !parent
    || Boolean(parent.closest('script, style, code, pre, textarea, input, select, [contenteditable="true"], [data-language-toggle], .dsvv-chat__message--user, .sidebar__user, .topbar__profile-copy strong'))
}

function translateTree(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    if (ignoredText(root)) return
    if (!originalText.has(root)) originalText.set(root, root.nodeValue ?? '')
    root.nodeValue = translate(originalText.get(root))
    return
  }

  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return
  const element = root.nodeType === Node.ELEMENT_NODE ? root : document.documentElement
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT)
  let node
  while ((node = walker.nextNode())) {
    if (ignoredText(node)) continue
    if (!originalText.has(node)) originalText.set(node, node.nodeValue ?? '')
    node.nodeValue = translate(originalText.get(node))
  }

  element.querySelectorAll('*').forEach(translateAttributes)
  if (element.nodeType === Node.ELEMENT_NODE) translateAttributes(element)
}

function translateAttributes(element) {
  const attributes = ['aria-label', 'aria-description', 'alt', 'placeholder', 'title']
  let originals = originalAttributes.get(element)
  if (!originals) {
    originals = new Map()
    originalAttributes.set(element, originals)
  }
  attributes.forEach((name) => {
    if (!element.hasAttribute(name)) return
    if (!originals.has(name)) originals.set(name, element.getAttribute(name))
    element.setAttribute(name, translate(originals.get(name) ?? ''))
  })
}

function updateToggle() {
  document.querySelectorAll('[data-language-toggle]').forEach((button) => {
    button.textContent = language === 'hi' ? 'English' : 'हिन्दी'
    button.setAttribute('aria-label', language === 'hi' ? 'Switch language to English' : 'भाषा हिंदी में बदलें')
    button.setAttribute('title', language === 'hi' ? 'Switch language to English' : 'भाषा हिंदी में बदलें')
  })
}

function placeToggle() {
  const target = document.querySelector('.topbar__actions, .app-page__header, .navbar__actions')
  if (target) {
    target.insertBefore(toggle, target.firstChild)
    toggle.classList.remove('language-toggle--floating')
    const mobileActions = document.querySelector('.navbar__mobile-actions')
    if (mobileActions && !mobileActions.querySelector('[data-language-toggle]')) {
      const mobileToggle = toggle.cloneNode(true)
      mobileActions.insertBefore(mobileToggle, mobileActions.firstChild)
    }
  } else {
    document.body.append(toggle)
    toggle.classList.add('language-toggle--floating')
  }
}

function applyLanguage() {
  document.documentElement.lang = language
  translateTree(document)
  if (originalTitle) document.title = translateTitle(originalTitle)
  updateToggle()
}

function setLanguage(nextLanguage) {
  language = nextLanguage
  try {
    window.localStorage.setItem(LANGUAGE_KEY, language)
  } catch {
    // The current page still switches language when persistent storage is unavailable.
  }
  applyLanguage()
}

export function initLanguage() {
  if (!document.body) return
  if (!toggle) {
    language = readLanguage()
    originalTitle = document.title
    toggle = document.createElement('button')
    toggle.type = 'button'
    toggle.className = 'language-toggle'
    toggle.dataset.languageToggle = ''
    document.addEventListener('click', (event) => {
      if (event.target.closest('[data-language-toggle]')) {
        setLanguage(language === 'hi' ? 'en' : 'hi')
      }
    })
    placeToggle()
    observer = new MutationObserver((records) => {
      records.forEach((record) => {
        record.addedNodes.forEach((node) => translateTree(node))
      })
    })
    observer.observe(document.body, { childList: true, subtree: true })
    window.addEventListener('storage', (event) => {
      if (event.key !== LANGUAGE_KEY) return
      language = event.newValue === 'hi' ? 'hi' : 'en'
      applyLanguage()
    })
  }
  placeToggle()
  applyLanguage()
}
